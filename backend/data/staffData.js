// ─── Helper utilities ──────────────────────────────────────────

const findStaffByName = (query) =>
  staffData.filter(s => s.name.toLowerCase().includes(query.toLowerCase()));

const findStaffByDepartment = (dept) =>
  staffData.filter(s => s.department.toLowerCase().includes(dept.toLowerCase()));

const findStaffBySubject = (subject) =>
  staffData.filter(s =>
    s.subjects.some(sub => sub.toLowerCase().includes(subject.toLowerCase()))
  );

const getStaffFreeTime = (name, day) => {
  const staff = findStaffByName(name)[0];
  if (!staff) return null;
  return staff.freeTime[day] || "Not available";
};

const findStaffForSubmission = (docType) =>
  staffData.filter(s =>
    s.submissions.some(sub => sub.toLowerCase().includes(docType.toLowerCase()))
  );

